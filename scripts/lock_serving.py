"""Resolve and hash CPU serving wheels inside the pinned Linux/Python image.

Run via the Docker command in docs/SERVING.md; not in the Windows environment.
Only stdlib is used. Review lock changes, then build and test before committing.
"""

import hashlib
import subprocess
import sys
import zipfile
from email.parser import BytesParser
from pathlib import Path


def main() -> None:
    if sys.platform != "linux":
        raise RuntimeError("Generate this platform lock inside the documented Linux image")
    root = Path(__file__).resolve().parents[1]
    wheels = root / "artifacts" / "docker-wheels"
    if wheels.exists() and any(wheels.iterdir()):
        raise RuntimeError("Use an empty artifacts/docker-wheels directory")
    subprocess.run(
        [
            sys.executable,
            "-m",
            "pip",
            "download",
            "--only-binary=:all:",
            "--dest",
            str(wheels),
            "-r",
            str(root / "requirements" / "serve.in"),
        ],
        check=True,
    )
    packages = []
    for wheel in wheels.glob("*.whl"):
        with zipfile.ZipFile(wheel) as archive:
            metadata_name = next(n for n in archive.namelist() if n.endswith(".dist-info/METADATA"))
            metadata = BytesParser().parsebytes(archive.read(metadata_name))
        with wheel.open("rb") as stream:
            digest = hashlib.file_digest(stream, "sha256").hexdigest()
        packages.append(f"{metadata['Name']}=={metadata['Version']} --hash=sha256:{digest}")
    header = (
        "# Linux amd64 / CPython 3.13 / CPU-only; generated by scripts/lock_serving.py\n"
        "--index-url https://pypi.org/simple\n"
        "--extra-index-url https://download.pytorch.org/whl/cpu\n"
        "--only-binary=:all:\n"
    )
    (root / "requirements" / "serve.lock").write_text(
        header + "\n".join(sorted(packages, key=str.lower)) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
